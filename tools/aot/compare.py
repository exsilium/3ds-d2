#!/usr/bin/env python3
"""Two recompilers' output compared (issue #144, scripts/docker.sh test
aot-compare): every file in either directory, the C and census.txt byte for
byte, the JSON reports but for their timings (analysis_s, emit_s). The C's
first line names the recompiler that wrote it: recompile.py's is read as the
Rust one's.

    python3 -I tools/aot/compare.py build/aot/cmp/py build/aot/cmp/rs
"""
import json
import os
import sys

TIMINGS = ("analysis_s", "emit_s")
GENERATOR = (b"/* Generated by tools/aot/recompile.py from Game.exe", b"/* Generated by tools/aot/recompile from Game.exe")


def load_json(path):
    with open(path) as fh:
        d = json.load(fh)
    for k in TIMINGS:
        d.pop(k, None)
    return d


def first_diff(a, b):
    """The first differing line of two texts, as (line number, a's, b's)."""
    la, lb = a.split(b"\n"), b.split(b"\n")
    for n, (x, y) in enumerate(zip(la, lb), 1):
        if x != y:
            return n, x[:200], y[:200]
    n = min(len(la), len(lb)) + 1
    return n, b"<end>" if len(la) < len(lb) else la[n - 1][:200], b"<end>" if len(lb) < len(la) else lb[n - 1][:200]


def main():
    da, db = sys.argv[1], sys.argv[2]
    names = sorted(set(os.listdir(da)) | set(os.listdir(db)))
    bad = 0
    for name in names:
        pa, pb = os.path.join(da, name), os.path.join(db, name)
        if not os.path.isfile(pa) or not os.path.isfile(pb):
            print("only in %s: %s" % (da if os.path.isfile(pa) else db, name))
            bad += 1
            continue
        if name.endswith(".json"):
            same = load_json(pa) == load_json(pb)
            note = "" if same else ": the reports differ"
        else:
            with open(pa, "rb") as fh:
                a = fh.read()
            with open(pb, "rb") as fh:
                b = fh.read()
            if name.endswith((".c", ".h")):
                a, b = (x.replace(*GENERATOR, 1) for x in (a, b))
            same = a == b
            note = ""
            if not same:
                n, x, y = first_diff(a, b)
                note = ": first at line %d\n    %s\n    %s" % (n, x.decode(errors="replace"), y.decode(errors="replace"))
        print("%s %s (%d bytes)%s" % ("same" if same else "DIFFERS", name, os.path.getsize(pa), note))
        bad += not same
    print("RESULT aot.compare %s (%d files, %d differ)" % ("PASS" if not bad else "FAIL", len(names), bad))
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
